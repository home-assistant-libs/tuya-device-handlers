"""Generate .github/copilot-instructions.md from AGENTS.md and the PR template.

Copilot code review does not read AGENTS.md, so its content is copied into
the file Copilot does read, prefixed with review-specific instructions.
"""

from pathlib import Path
import re

ROOT = Path(__file__).parent.parent
AGENTS_FILE = ROOT / "AGENTS.md"
OUTPUT_FILE = ROOT / ".github" / "copilot-instructions.md"
PR_TEMPLATE_FILE = ROOT / ".github" / "PULL_REQUEST_TEMPLATE.md"

# Relative Markdown links, rebased because the output lives in .github/
LOCAL_LINK_PATTERN = re.compile(r"\]\((?!https?://|#|/)([^)]+)\)")

GENERATED_MESSAGE = (
    f"<!-- Automatically generated by {Path(__file__).name}, do not edit -->"
)

COPILOT_REVIEW_INSTRUCTIONS = """
# Copilot code review instructions

- Start review comments with a short, one-sentence summary of the suggested fix.
- Do not comment on code style, formatting or linting issues; ruff, pylint,
  ty and prettier enforce these in CI.
- When reviewing changes under `src/tuya_device_handlers/devices/`,
  `tests/devices/` or `tests/fixtures/devices/`, use the `tuya-device-quirk`
  skill as the primary reference.
- Flag any rename, move or signature change of the public API surface listed
  below: Home Assistant Core imports these symbols, so such a change needs a
  coordinated release.
- Flag comments that over-explain straightforward code, narrate the obvious,
  or read like AI commentary (multi-sentence justifications for a single line).
- A pull request with a dependency version bump should only contain changes
  required for the version bump. If it includes other changes, request that
  they are removed from the pull request.
- Pull requests adding or changing a device quirk must be titled
  "Add quirk for <product name> (<product id>)" or
  "Amend quirk for <product name> (<product id>)".
- Do not ask contributors to use a feature branch instead of their fork's
  `main` branch.
- Do not ask contributors to force-push, except to remove personal data
  (Wi-Fi name, IP or MAC address, serial number, …) from the branch history.
- Check that the pull request description follows the template included
  below, with every section present and filled in.
- Skip the pull request template check for pull requests generated by
  Renovate. All other review instructions still apply to them.

## Pull request template

The pull request description must follow this template (from
`.github/PULL_REQUEST_TEMPLATE.md`):

```markdown
{pr_template}
```
"""


def generate_output() -> str:
    """Generate the copilot-instructions.md content."""
    review_instructions = COPILOT_REVIEW_INSTRUCTIONS.replace(
        "{pr_template}", PR_TEMPLATE_FILE.read_text(encoding="utf-8").strip()
    )
    return "\n".join(
        [
            GENERATED_MESSAGE,
            review_instructions,
            LOCAL_LINK_PATTERN.sub(
                r"](../\1)", AGENTS_FILE.read_text(encoding="utf-8").strip()
            ),
            "",
        ]
    )


def main() -> None:
    """Write the generated file."""
    OUTPUT_FILE.write_text(generate_output(), encoding="utf-8")


if __name__ == "__main__":
    main()
